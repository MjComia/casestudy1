-- =============================================================================
-- Wide World Importers (WWI) - OLAP Dimensional Model Schema DDL
-- Target Engine: PostgreSQL 15+
-- Schema: olap
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS olap;

-- -----------------------------------------------------------------------------
-- 1. DIMENSION TABLES
-- -----------------------------------------------------------------------------

-- Date Dimension (Generated calendar with Fiscal Year starting November 1)
CREATE TABLE IF NOT EXISTS olap.dim_date (
    date_key                    INT PRIMARY KEY,            -- YYYYMMDD
    calendar_date               DATE NOT NULL UNIQUE,
    day_number                  INT NOT NULL,
    day_name                    VARCHAR(10) NOT NULL,
    weekday_number              INT NOT NULL,               -- 1=Monday, 7=Sunday
    is_weekend                  BOOLEAN NOT NULL,
    calendar_month_number       INT NOT NULL,
    calendar_month_name         VARCHAR(15) NOT NULL,
    calendar_quarter            INT NOT NULL,
    calendar_year               INT NOT NULL,
    fiscal_month_number         INT NOT NULL,               -- 1=November ... 12=October
    fiscal_quarter              INT NOT NULL,               -- Q1: Nov-Jan, Q2: Feb-Apr, Q3: May-Jul, Q4: Aug-Oct
    fiscal_year                 INT NOT NULL
);

-- City Dimension (Geographic hierarchy)
CREATE TABLE IF NOT EXISTS olap.dim_city (
    city_key                    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id                     INT NOT NULL,
    city_name                   VARCHAR(50) NOT NULL,
    state_province_code         VARCHAR(5) NOT NULL,
    state_province_name         VARCHAR(50) NOT NULL,
    country_name                VARCHAR(60) NOT NULL,
    continent                   VARCHAR(30) NOT NULL,
    sales_territory             VARCHAR(50) NOT NULL,
    region                      VARCHAR(30) NOT NULL,
    subregion                   VARCHAR(30) NOT NULL,
    latitude                    NUMERIC(10, 7),
    longitude                   NUMERIC(10, 7),
    latest_recorded_population  BIGINT
);

-- Customer Dimension (SCD Type 2 enabled)
CREATE TABLE IF NOT EXISTS olap.dim_customer (
    customer_key                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id                 INT NOT NULL,               -- Natural Key
    customer_name               VARCHAR(100) NOT NULL,
    customer_category_name      VARCHAR(50) NOT NULL,
    buying_group_name           VARCHAR(50),
    delivery_city_name          VARCHAR(50),
    delivery_state_province_name VARCHAR(50),
    credit_limit                NUMERIC(18, 2),
    account_opened_date         DATE,
    standard_discount_percentage NUMERIC(18, 3),
    payment_days                INT,
    phone_number                VARCHAR(20),
    website_url                 VARCHAR(256),
    delivery_address_line       VARCHAR(100),
    valid_from                  DATE NOT NULL,
    valid_to                    DATE NOT NULL DEFAULT '9999-12-31',
    is_current                  BOOLEAN NOT NULL DEFAULT TRUE
);

-- Employee / Salesperson Dimension
CREATE TABLE IF NOT EXISTS olap.dim_employee (
    employee_key                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id                   INT NOT NULL,
    full_name                   VARCHAR(50) NOT NULL,
    preferred_name              VARCHAR(50),
    is_employee                 BOOLEAN NOT NULL,
    is_salesperson              BOOLEAN NOT NULL
);

-- Stock Item (Product) Dimension
CREATE TABLE IF NOT EXISTS olap.dim_stock_item (
    stock_item_key              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id               INT NOT NULL,
    stock_item_name             VARCHAR(100) NOT NULL,
    supplier_id                 INT,
    color_name                  VARCHAR(20),
    unit_package_type           VARCHAR(50),
    outer_package_type          VARCHAR(50),
    brand                       VARCHAR(50),
    size                        VARCHAR(20),
    lead_time_days              INT,
    quantity_per_outer          INT,
    is_chiller_stock            BOOLEAN,
    barcode                     VARCHAR(50),
    tax_rate                    NUMERIC(18, 3),
    unit_price                  NUMERIC(18, 2),
    recommended_retail_price    NUMERIC(18, 2),
    typical_weight_per_unit     NUMERIC(18, 3)
);

-- -----------------------------------------------------------------------------
-- 2. FACT TABLES
-- -----------------------------------------------------------------------------

-- Fact Orders (Grain: One row per order line)
CREATE TABLE IF NOT EXISTS olap.fact_order (
    order_line_key              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id                    INT NOT NULL,
    order_line_id               INT NOT NULL,
    customer_purchase_order_number VARCHAR(20),
    order_date_key              INT NOT NULL REFERENCES olap.dim_date(date_key),
    customer_key                INT NOT NULL REFERENCES olap.dim_customer(customer_key),
    stock_item_key              INT NOT NULL REFERENCES olap.dim_stock_item(stock_item_key),
    salesperson_key             INT NOT NULL REFERENCES olap.dim_employee(employee_key),
    picked_by_key               INT NOT NULL REFERENCES olap.dim_employee(employee_key),
    delivery_city_key           INT NOT NULL REFERENCES olap.dim_city(city_key),
    quantity                    INT NOT NULL,
    unit_price                  NUMERIC(18, 2) NOT NULL,
    tax_rate                    NUMERIC(18, 3) NOT NULL,
    picked_quantity             INT,
    is_undersupply_backordered  BOOLEAN,
    backorder_order_id          INT,
    picking_completed_when      TIMESTAMP
);

-- Fact Sales (Grain: One row per invoice line)
CREATE TABLE IF NOT EXISTS olap.fact_sale (
    sale_key                    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    invoice_id                  INT NOT NULL,
    invoice_line_id             INT NOT NULL,
    order_id                    INT,
    customer_purchase_order_number VARCHAR(20),
    invoice_date_key            INT NOT NULL REFERENCES olap.dim_date(date_key),
    customer_key                INT NOT NULL REFERENCES olap.dim_customer(customer_key),
    stock_item_key              INT NOT NULL REFERENCES olap.dim_stock_item(stock_item_key),
    salesperson_key             INT NOT NULL REFERENCES olap.dim_employee(employee_key),
    delivery_city_key           INT NOT NULL REFERENCES olap.dim_city(city_key),
    quantity                    INT NOT NULL,
    unit_price                  NUMERIC(18, 2) NOT NULL,
    tax_rate                    NUMERIC(18, 3) NOT NULL,
    tax_amount                  NUMERIC(18, 2) NOT NULL,
    line_profit                 NUMERIC(18, 2) NOT NULL,
    extended_price              NUMERIC(18, 2) NOT NULL,
    days_order_to_invoice       INT,
    days_invoice_to_delivery    INT,
    confirmed_delivery_time     TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- 3. INDEXES FOR HIGH-PERFORMANCE ANALYTICS
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_fact_order_date ON olap.fact_order(order_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_order_customer ON olap.fact_order(customer_key);
CREATE INDEX IF NOT EXISTS idx_fact_order_stock ON olap.fact_order(stock_item_key);

CREATE INDEX IF NOT EXISTS idx_fact_sale_date ON olap.fact_sale(invoice_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_sale_customer ON olap.fact_sale(customer_key);
CREATE INDEX IF NOT EXISTS idx_fact_sale_stock ON olap.fact_sale(stock_item_key);
CREATE INDEX IF NOT EXISTS idx_fact_sale_employee ON olap.fact_sale(salesperson_key);
CREATE INDEX IF NOT EXISTS idx_fact_sale_city ON olap.fact_sale(delivery_city_key);
